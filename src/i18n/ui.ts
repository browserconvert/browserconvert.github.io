export type TranslationKey = keyof typeof ui.en;

export function useTranslations(lang: SupportedLanguage = 'en') {
  return function t(key: TranslationKey): any {
    const dict = ui[lang] || ui.en;
    return dict[key] !== undefined ? dict[key] : (ui.en[key] !== undefined ? ui.en[key] : key);
  };
}

export function getLocalizedPath(currentLang: SupportedLanguage, targetLang: SupportedLanguage, path: string = ''): string {
  const cleanPath = path.replace(/^\/(en|es|pt|de|fr|ja|zh|ru)/, '').replace(/^\//, '');
  if (targetLang === 'en') {
    return cleanPath ? `/${cleanPath}` : '/';
  }
  return cleanPath ? `/${targetLang}/${cleanPath}` : `/${targetLang}/`;
}
